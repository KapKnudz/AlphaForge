def detail(
    entry, body="Interim report January-June 2026. Revenue 2847 MSEK. Operating profit 312 MSEK."
):
    return f'<html><head><meta property="article:published_time" content="{entry["content"]["publish_date"]}"><link rel="canonical" href="{entry["url"]}"></head><body><h1>{entry["content"]["title"]}</h1><div class="release-body"><p>{body}</p><a class="mfn-primary" href="{entry["content"]["attachments"][0]["url"]}">PDF report</a></div></body></html>'


def run(lane, entries, *, bodies=None, scraper=None, pages=None, limits=None, fetch=True):
    conn, company_id, store = lane
    requested = []
    documents = {
        entry["url"]: detail(
            entry,
            (bodies or {}).get(
                entry["url"],
                "Interim report January-June 2026. Revenue 2847 MSEK. Operating profit 312 MSEK.",
            ),
        )
        for entry in entries
    }
    documents.update(pages or {})

    def transport(_method, url, **_kwargs):
        requested.append(url)
        if "?offset=" in url:
            assert ".html?" not in url, "valid null-tag JSON must not use HTML fallback"
            return SimpleNamespace(
                status_code=200,
                headers={"Content-Type": "application/json"},
                text=json.dumps({"items": entries}),
            )
        return SimpleNamespace(status_code=200, text=documents[url])

    def download(_method, url, **_kwargs):
        assert fetch, "unchanged retained candidates must not issue PDF HTTP"
        requested.append(url)
        return SimpleNamespace(
            status_code=200,
            headers={"Content-Type": "application/pdf"},
            content=pdf(PDF_TEXT + (" Independent Swedish edition." if "sv.pdf" in url else "")),
        )

    with (
        patch("alphaforge.providers.mfn.scraper.request_with_retry", side_effect=transport),
        patch("alphaforge.providers.mfn.scraper.time.sleep"),
        patch("alphaforge.evidence.flow.request_with_retry", side_effect=download),
    ):
        result = OneCompanyEvidenceFlow(
            conn,
            scraper=scraper or MfnScraper(max_articles=60),
            artifact_store=store,
            now=lambda: (
                NOW
                + timedelta(
                    seconds=conn.execute(
                        "SELECT count(*) FROM evidence_observation_batches"
                    ).fetchone()[0]
                    + 1
                )
            ),
            limits=limits or EvidenceResourceLimits(),
        ).run(company_id, as_of=AS_OF)
    return result, requested


def view(lane):
    conn, company_id, store = lane
    return load_evidence_view(conn, company_id=company_id, as_of=AS_OF, artifact_store=store)


def gate(packet, company_id):
    return (
        AgentReadinessGate()
        .assess(
            SimpleNamespace(
                company_id=company_id,
                ticker="FLOW",
                ranking_model="general",
                research_evidence={"evidence_lane": True, "evidence_packet": packet},
                full_results={
                    "reverse_dcf": {"status": "available"},
                    "valuation": {"ev_ebit_guardrail_low": 5, "ev_ebit_guardrail_high": 20},
                },
            )
        )
        .status
    )


@pytest.mark.parametrize("tags", [None, "archive:report:pdf", {"archive:report:pdf": True}, []])
def test_raw_null_and_malformed_tags_preserve_admission_and_window(lane, tags):
    fixture = json.loads((Path(__file__).parent / "fixtures/mfn/aq_null_tag_feed.json").read_text())
    explicit = item()
    explicit["properties"]["tags"] = None
    explicit["content"]["attachments"][0]["tags"] = tags
