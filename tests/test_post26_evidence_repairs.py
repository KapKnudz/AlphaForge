def test_rule_change_corrects_wrong_nonnull_observation_without_mutating_history(lane):
    conn, company_id, store = lane
    entry = item(title="Strategic and operational progress")
    body = "Bokslutskommuniké januari-december 2025. Från första kvartalet 2026."
    # Scraper's real detail parser supplies precisely this body, including h1.
    from alphaforge.providers.mfn.scraper import _parse_html

    parsed_body = _parse_html(detail(entry, body), corroborated_report=True)["body"]
    stale_rules = {**report_rules_metadata(), "version": 4, "fingerprint": "old-fiscal-rules"}
    recorder = RevisionRecorder(
        conn,
        store,
        company_id=company_id,
        as_of=AS_OF,
        source_input_fingerprint="old-feed",
        report_rules_fingerprint=stale_rules["fingerprint"],
        effective_at="2026-09-29T00:00:00.000000Z",
        max_pages=50,
        max_pdf_bytes=25 * 1024 * 1024,
    )
    content = pdf()
    import hashlib

    old = recorder.record(
        {
            "source_url": entry["url"],
            "title": entry["content"]["title"],
            "published_at": entry["content"]["publish_date"],
            "report_kind": "quarterly",
            "document_type": "INTERIM_Q2",
            "fiscal_period": "2026/2026-q1",
            "fiscal_period_source": "legacy_narrative",
            "content_text": parsed_body,
            "lang": "en",
            "language_evidence": "filename",
            "mfn_slug": "all/a/flow",
            "attachment_tier": "mfn-primary",
        },
        eligibility="eligible",
        eligibility_reason="deterministic_report_admission",
        downloaded=PdfDownload(
            entry["content"]["attachments"][0]["url"],
            "application/pdf",
            200,
            content,
            hashlib.sha256(content).hexdigest(),
        ),
        extracted=ResearchDocumentIngestionService(conn).extract_pdf_pages(content, max_pages=50),
    )
    manifest = load_evidence_selection_manifest(
        conn, company_id=company_id, as_of=AS_OF, report_rules=stale_rules, artifact_store=store
    )
    old_packet = build_frozen_evidence_packet(
        conn,
        company_id=company_id,
        as_of=AS_OF,
        report_rules=stale_rules,
        selection_manifest=manifest,
        artifact_store=store,
    )
    persist_evidence_packet(conn, company_id=company_id, as_of=AS_OF, packet=old_packet)
    persist_evidence_selection_manifest(conn, manifest, packet_hash=old_packet["packet_hash"])
    historical_json = conn.execute(
        "SELECT manifest_json FROM evidence_selection_manifests WHERE manifest_id=?",
        (manifest.manifest_id,),
    ).fetchone()[0]
    assert validate_frozen_packet(old_packet)
    assert load_evidence_packet(conn, company_id, AS_OF) is None
    assert gate(old_packet, company_id) == "evidence_blocked"
    repaired, _ = run(lane, [entry], bodies={entry["url"]: body}, fetch=False)
    assert repaired.status == "complete"
    assert repaired.pdf_fetch_attempts == 0
    current = current_candidate_observations(conn, company_id=company_id, as_of=AS_OF)[0]
    assert current["fiscal_period"] == "2025/2025-q4"
    assert current["candidate_observation_id"] != old["candidate_observation_id"]
    assert (
        conn.execute(
            "SELECT fiscal_period FROM evidence_candidate_observations WHERE candidate_observation_id=?",
            (old["candidate_observation_id"],),
        ).fetchone()[0]
        == "2026/2026-q1"
    )
    assert (
        conn.execute(
            "SELECT manifest_json FROM evidence_selection_manifests WHERE manifest_id=?",
            (manifest.manifest_id,),
        ).fetchone()[0]
        == historical_json
    )
    assert repaired.packet_hash != old_packet["packet_hash"]
    assert gate(repaired.packet, company_id) == "ready"


